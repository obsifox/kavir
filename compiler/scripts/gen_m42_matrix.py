#!/usr/bin/env python3
"""scripts/gen_m42_matrix.py -- M4.2 aggregate-ABI regression matrix.

Generated for independent-verification round 2, bug 1 (SIGSEGV: the
sret pointer collided with a stack-parameter word because the frame
vreg area was sized from dest-writing instructions only, ignoring
parameter words). The matrix pins the fixed behaviour three-way
(ELF == interpreter == tests/reference.py).

Dimensions (full cross product, 7 x 3 x 3 x 3 = 189 programs):

  aggregate size   4, 8, 12, 16, 20, 24, 32 bytes (1, 2, 3, 4, 5, 6, 8
                   4-byte words); 1-word -> one register, 2-word -> one
                   packed register, >2-word -> stack + hidden-pointer
                   return (ADR-011)
  callee locals    0, 1, 3 (0 locals with a direct param return was the
                   crashing shape)
  return kind      param  = callee returns its aggregate parameter
                           (directly or through locals that provably
                           preserve the value)
                   built  = callee builds the result from the parameter
                           in a fresh local
                   chain  = value flows through three calls, each with
                           its own frame and return class
  scalar context   s0 = no scalars
                   s3 = 3 scalars after the aggregate (registers)
                   s7 = 3 scalars before + 4 after the aggregate
                        (registers AND stack units on both sides)

Every s3/s7 program also round-trips the scalars through a separate
scalar-only call and prints the result, so the scalar register/stack
mapping is observable, not just the aggregate one.

Run: python3 scripts/gen_m42_matrix.py [--force]
Writes tests/cases_m42/m42_w<words>_loc<n>_<kind>_<ctx>.k
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "tests", "cases_m42")

SIZES = [1, 2, 3, 4, 5, 6, 8]          # words (4 bytes each)
LOCALS = [0, 1, 3]
KINDS = ["param", "built", "chain"]
CTX = ["s0", "s3", "s7"]


def struct_def(w):
    lines = ["struct S%d {" % w]
    for i in range(w):
        lines.append("    f%d: i32," % i)
    lines.append("}")
    return "\n".join(lines)


def field_val(i, w):
    return (i + 1) * 11 + w


def lit(w, base=0):
    pairs = ", ".join("f%d: %d" % (i, field_val(i, w) + base)
                      for i in range(w))
    return "S%d { %s }" % (w, pairs)


def scalar_names(k):
    return "abcdefg"[:k]


def sig_after(w, ctx):
    """aggregate first, then scalars (s3)."""
    if ctx == "s0":
        return "x: S%d" % w
    if ctx == "s3":
        return "x: S%d, a: i32, b: i32, c: i32" % w
    raise ValueError(ctx)


def sig_split(w, ctx):
    """s7: 3 scalars BEFORE the aggregate + 4 after (max ABI mix)."""
    if ctx == "s7":
        return ("a: i32, b: i32, c: i32, x: S%d, "
                "d: i32, e: i32, f: i32, g: i32" % w)
    return sig_after(w, ctx)


def arg_after(ctx, prefix=""):
    if ctx == "s0":
        return prefix
    if ctx == "s3":
        return "%s, 1, 2, 3" % prefix
    raise ValueError(ctx)


def arg_split(ctx):
    if ctx == "s7":
        return "1, 2, 3, %s, 4, 5, 6, 7" % "%s"
    return arg_after(ctx)


def locals_body(w, n, kind):
    """Body prefix inside the callee; returns (lines, expr_to_return)."""
    if kind == "built":
        if n == 0:
            # a built result needs at least the constructed local itself
            return ([], "S%d { %s }" % (
                w, ", ".join("f%d: x.f%d + %d" % (i, i, i)
                             for i in range(w))))
        lines = ["    let t1: i32 = 7;"]
        if n >= 3:
            lines += ["    let t2: i32 = t1 + 1;",
                      "    let t3: i32 = t2 + 2;"]
        fields = ", ".join("f%d: x.f%d + t1 * 0 + %d" % (i, i, i)
                           for i in range(w))
        lines.append("    let r: S%d = S%d { %s };" % (w, w, fields))
        return (lines, "r")
    # kind == param
    if n == 0:
        return ([], "x")
    lines = ["    let mut y: S%d = x;" % w]
    if n == 1:
        lines.append("    y.f0 = y.f0 + 0;")
    else:
        lines += ["    let t1: i32 = y.f0 + 0;",
                  "    let t2: i32 = t1 + 1;",
                  "    let t3: i32 = t2 + 2;",
                  "    y.f%d = y.f%d + t3 * 0;" % (w - 1, w - 1)]
    return (lines, "y")


def gen(w, n, kind, ctx):
    bytes_ = 4 * w
    head = [
        "// M4.2 regression matrix (ADR-011; verification round 2 bug 1):",
        "// %d bytes (%d words), locals=%d, kind=%s, ctx=%s." %
        (bytes_, w, n, kind, ctx),
        "// Generated by scripts/gen_m42_matrix.py -- do not edit.",
        struct_def(w),
        "",
    ]
    body = []

    if ctx == "s3":
        body += [
            "fn scal(a: i32, b: i32, c: i32) -> i32 {",
            "    return a + 2 * b + 4 * c;",
            "}",
            "",
        ]
    elif ctx == "s7":
        body += [
            "fn scal(a: i32, b: i32, c: i32, d: i32, e: i32, "
            "f: i32, g: i32) -> i32 {",
            "    return a + 2 * b + 4 * c + 8 * d + 16 * e "
            "+ 32 * f + 64 * g;",
            "}",
            "",
        ]
    if kind == "chain":
        # three hops; each hop returns through its own frame; locals
        # cycle 0/1/3 across hops so every hop shape differs. Each hop
        # forwards its OWN parameter list verbatim (value-preserving),
        # so the s7 signature's scalars cross register AND stack
        # classes at every hop.
        for hop in (3, 2, 1):
            ln = [0, 1, 3][(3 - hop) % 3]
            hb, ret = locals_body(w, ln, "param")
            body.append("fn hop%d(%s) -> S%d {" %
                        (hop, sig_split(w, ctx), w))
            body += hb
            if hop > 1:
                call = ", ".join(p.split(":")[0].strip() for p in
                                 sig_split(w, ctx).split(","))
                body.append("    return hop%d(%s);" % (hop - 1, call))
            else:
                body.append("    return %s;" % ret)
            body.append("}")
            body.append("")
        call_main = "v"
        if ctx == "s7":
            call_main = "1, 2, 3, v, 4, 5, 6, 7"
        elif ctx == "s3":
            call_main = "v, 1, 2, 3"
        body += [
            "fn main() -> i32 {",
            "    let v: S%d = %s;" % (w, lit(w)),
            "    let r: S%d = hop1(%s);" % (w, call_main),
            "    print(r.f0);",
            "    print(r.f%d);" % (w - 1),
        ]
    else:
        hb, ret = locals_body(w, n, kind)
        body.append("fn ident(%s) -> S%d {" % (sig_split(w, ctx), w))
        body += hb
        body.append("    return %s;" % ret)
        body.append("}")
        body.append("")
        call_main = "v"
        if ctx == "s7":
            call_main = "1, 2, 3, v, 4, 5, 6, 7"
        elif ctx == "s3":
            call_main = "v, 1, 2, 3"
        body += [
            "fn main() -> i32 {",
            "    let v: S%d = %s;" % (w, lit(w)),
            "    let r: S%d = ident(%s);" % (w, call_main),
            "    print(r.f0);",
            "    print(r.f%d);" % (w - 1),
        ]
    if ctx == "s3":
        body.append("    print(scal(1, 2, 3));")
    elif ctx == "s7":
        body.append("    print(scal(1, 2, 3, 4, 5, 6, 7));")
    body += ["    return 0;", "}"]
    return "\n".join(head + body) + "\n"


def main():
    force = "--force" in sys.argv
    os.makedirs(OUT, exist_ok=True)
    count = 0
    for w in SIZES:
        for n in LOCALS:
            for kind in KINDS:
                for ctx in CTX:
                    name = "m42_w%d_loc%d_%s_%s.k" % (w, n, kind, ctx)
                    path = os.path.join(OUT, name)
                    if os.path.exists(path) and not force:
                        continue
                    with open(path, "w", encoding="ascii") as f:
                        f.write(gen(w, n, kind, ctx))
                    count += 1
    print("wrote %d programs into %s" % (count, OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
