M4_ENUM_MATCH = HEADER + STRUCTS + ENUMS + """\
// Enums: constructors (bare and payload-carrying), exhaustive match
// with payload binding, and the wildcard as the final arm.
fn area(s: Shape) -> i32 {
    return match s {
        Shape.Dot => 0,
        Shape.Circle(r) => 3 * r * r,
        Shape.Rect(w, h) => w * h,
    };
}

fn label(s: Shape) -> i32 {
    return match s {
        Shape.Dot => 1,
        _ => 2,
    };
}

fn nested(s: Shape) -> i32 {
    let mut i: i32 = 0;
    let mut acc: i32 = 0;
    while (i < 3) {
        acc = acc + match s {
            Shape.Dot => 1,
            Shape.Circle(r) => r,
            Shape.Rect(w, h) => w + h,
        };
        i = i + 1;
    }
    return acc;
}

fn handle(r: Res) -> i32 {
    return match r {
        Res.Ok(p) => p.x + p.y,
        Res.Bad => 0 - 99,
    };
}

fn main() -> i32 {
    print(area(Shape.Dot));
    print(area(Shape.Circle(4)));
    print(area(Shape.Rect(3, 5)));
    print(label(Shape.Dot));
    print(label(Shape.Circle(1)));
    print(nested(Shape.Rect(2, 3)));
    print(handle(Res.Ok(Point { x: 2, y: 3 })));
    print(handle(Res.Bad));
    return 0;
}
"""

M4_OPTION_BASIC = HEADER + STRUCTS + """\
// Option[T] as the builtin mono enum: None/Some(i32), Option[Point]
// (aggregate payload), nested Option[Option[i32]]; Some carries the
// value by copy (no aliasing).
fn get(o: Option[i32]) -> i32 {
    return match o { Option.None => 0 - 1, Option.Some(v) => v };
}

fn outer(o: Option[Option[i32]]) -> i32 {
    return match o {
        Option.None => 0,
        Option.Some(inner) => match inner {
            Option.None => 1,
            Option.Some(v) => v,
        },
    };
}

fn main() -> i32 {
    let some: Option[i32] = Option.Some(42);
    let none: Option[i32] = Option.None;
    print(get(some));
    print(get(none));
    let p: Option[Point] = Option.Some(Point { x: 7, y: 9 });
    print(match p { Option.None => 0, Option.Some(pt) => pt.x * pt.y });
    print(outer(Option.None));
    print(outer(Option.Some(Option.None)));
    print(outer(Option.Some(Option.Some(5))));
    return 0;
}
"""

M4_OPTION_ABI = HEADER + STRUCTS + """\
// Option through the aggregate ABI: Option[i32] is 2 words (<=8B =>
// ONE register, low = tag, high = payload); Option[Point] is 3 words
// (memory class: stack words in, hidden-pointer return out).
fn or_default(o: Option[i32], d: i32) -> i32 {
    return match o { Option.None => d, Option.Some(v) => v };
}

fn flip(o: Option[i32]) -> Option[i32] {
    let t: i32 = match o { Option.None => 1, Option.Some(v) => 0 };
    if (t == 1) { return Option.Some(100); }
    return Option.None;
}

fn opt_x(o: Option[Point]) -> i32 {
    return match o { Option.None => 0, Option.Some(p) => p.x };
}

fn opt_y(o: Option[Point]) -> i32 {
    return match o { Option.None => 0, Option.Some(p) => p.y };
}

fn mk_point(k: i32) -> Point {
    return Point { x: k, y: 2 * k };
}

fn main() -> i32 {
    print(or_default(Option.Some(9), 5));
    print(or_default(Option.None, 5));
    let f: Option[i32] = flip(Option.None);
    let g: Option[i32] = flip(Option.Some(3));
    print(match f { Option.None => 0 - 1, Option.Some(v) => v });
    print(match g { Option.None => 0 - 1, Option.Some(v) => v });
    let p: Point = mk_point(6);
    let mut q: Point = Point { x: 0, y: 0 };
    q.x = opt_x(Option.Some(p));
    q.y = opt_y(Option.Some(p));
    print(q.x);
    print(q.y);
    q.x = opt_x(Option.None);
    q.y = opt_y(Option.None);
    print(q.x);
    print(q.y);
    print(p.x);
    print(p.y);
    return 0;
}
"""

M4_TRAP_FIELD = HEADER + STRUCTS + """\
// Trap positions inside aggregate arithmetic: the trap line must
// carry the exact operator position; prints before the trap pin the
// stdout/stderr interleaving (ADR-008).
fn main() -> i32 {
    let mut p: Point = Point { x: 2147483647, y: 1 };
    print(1);
    print(p.x + p.y);
    print(2);
    p.x = -2147483648;
    print(p.x / 0);
    print(3);
    return 0;
}
"""

M4_TRAP_MATCH = HEADER + STRUCTS + ENUMS + """\
// Traps inside a match arm: the arm's operator position is the trap
// site; stdout shows the prints that ran before the trap.
fn area(s: Shape) -> i32 {
    return match s {
        Shape.Dot => 0,
        Shape.Circle(r) => r * 2147483647,
        Shape.Rect(w, h) => w * h,
    };
}

fn main() -> i32 {
    print(1);
    print(area(Shape.Dot));
    print(2);
    print(area(Shape.Circle(3)));
    print(3);
    return 0;
}
"""


