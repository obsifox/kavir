def write(name, text):
    path = os.path.join(CASES, name)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", path)


# ------------------------------------------------------------- ABI tests

M4_ARGS_REGISTER = HEADER + STRUCTS + """\
// 2-word values (8 bytes) travel in ONE integer register: word0 in the
// low 32 bits, word1 in the high 32 bits (SysV INTEGER eightbyte shape,
// ADR-011 decision 2). Weights 1 and 256 make any swap or loss
// observable. Argument expressions may themselves call (register
// pressure inside argument evaluation).
fn wpair(p: Pair) -> i32 {
    return p.lo + 256 * p.hi;
}

fn mkpair(a: i32, b: i32) -> Pair {
    return Pair { lo: a, hi: b };
}

fn takes2(p1: Pair, p2: Pair, s: i32) -> i32 {
    return wpair(p1) + wpair(p2) + s;
}

fn main() -> i32 {
    let p: Pair = Pair { lo: 3, hi: 4 };
    print(wpair(p));
    print(wpair(mkpair(0 - 1, 1)));
    print(wpair(mkpair(mkpair(1, 2).lo, 6)));
    print(takes2(Pair { lo: 1, hi: 0 }, mkpair(0, 5), 2));
    print(takes2(mkpair(1, 1), Pair { lo: 2, hi: 2 }, mkpair(9, 9).lo));
    return 0;
}
"""

M4_ARGS_STACK = HEADER + STRUCTS + """\
// Values wider than 8 bytes ALWAYS travel through memory (ADR-011
// decision 2): each argument's words are packed into 8-byte stack
// units, leftmost argument at the lowest address. This exercises
// 3-word and 5-word arguments mixed with scalars, and the callee-side
// unpacking; weights make every slot position observable.
fn wtri(t: Tri) -> i32 {
    return t.a + 8 * t.b + 64 * t.c;
}

fn wpent(v: Pent) -> i32 {
    return v.a + 2 * v.b + 4 * v.c + 8 * v.d + 16 * v.e;
}

fn mixed3(s: i32, t: Tri, u: i32) -> i32 {
    return s + wtri(t) + 1024 * u;
}

fn wide2(t: Tri, v: Pent) -> i32 {
    return wtri(t) + wpent(v);
}

fn main() -> i32 {
    print(wtri(Tri { a: 1, b: 1, c: 1 }));
    print(wpent(Pent { a: 1, b: 1, c: 1, d: 1, e: 1 }));
    print(mixed3(5, Tri { a: 1, b: 0, c: 0 }, 2));
    print(mixed3(0, Tri { a: 0, b: 1, c: 0 }, 0));
    print(wide2(Tri { a: 1, b: 2, c: 4 }, Pent { a: 1, b: 0, c: 0, d: 0, e: 0 }));
    print(wide2(Tri { a: 0, b: 0, c: 0 }, Pent { a: 0, b: 1, c: 0, d: 1, e: 0 }));
    return 0;
}
"""

M4_ARGS_HIDDEN = HEADER + STRUCTS + """\
// Returns wider than 8 bytes use the hidden-pointer shape (ADR-011
// decision 2): the caller passes RDI = address of its return scratch,
// the callee stores the result words there. This drives 3-word and
// 5-word returns through functions whose frames are deep (locals +
// while loops) and mixes register- and stack-class parameters.
fn mktri(a: i32, b: i32, c: i32) -> Tri {
    let t: Tri = Tri { a: a, b: b, c: c };
    return t;
}

fn mkpent(k: i32) -> Pent {
    let v: Pent = Pent { a: k, b: 2 * k, c: 3 * k, d: 4 * k, e: 5 * k };
    return v;
}

fn scale(t: Tri, k: i32) -> Tri {
    let mut i: i32 = 0;
    let mut acc: Tri = Tri { a: 0, b: 0, c: 0 };
    while (i < k) {
        acc = Tri { a: acc.a + t.a, b: acc.b + t.b, c: acc.c + t.c };
        i = i + 1;
    }
    return acc;
}

fn wtri(t: Tri) -> i32 {
    return t.a + 8 * t.b + 64 * t.c;
}

fn wpent(v: Pent) -> i32 {
    return v.a + 2 * v.b + 4 * v.c + 8 * v.d + 16 * v.e;
}

fn main() -> i32 {
    let t: Tri = mktri(3, 5, 7);
    let v: Pent = mkpent(2);
    let s: Tri = scale(t, 3);
    print(t.a);
    print(t.b);
    print(t.c);
    print(wtri(t));
    print(wpent(v));
    print(wtri(s));
    print(wtri(mktri(1, 1, 1)));
    return 0;
}
"""

M4_MIX_8ARGS = HEADER + STRUCTS + ENUMS + """\
// Eight arguments mixing every class: scalars (registers + stack),
// 2-word register-class aggregates, 3-word stack-class aggregates and
// a 2-word Option[i32]. Bit weights pin every position.
fn mix(a: i32, p: Pair, b: i32, t: Tri, o: Option[i32], c: i32,
       p2: Pair, d: i32) -> i32 {
    let ov: i32 = match o { Option.None => 0, Option.Some(v) => v };
    let w: i32 = a + 2 * (p.lo + p.hi) + 4 * b + 8 * (t.a + t.b + t.c)
               + 16 * ov + 32 * c + 64 * (p2.lo + p2.hi) + 128 * d;
    return w;
}

fn main() -> i32 {
    print(mix(1, Pair { lo: 1, hi: 1 }, 1,
              Tri { a: 1, b: 1, c: 1 }, Option.None, 1,
              Pair { lo: 1, hi: 1 }, 1));
    print(mix(1, Pair { lo: 0, hi: 1 }, 0,
              Tri { a: 0, b: 1, c: 0 }, Option.Some(3), 0,
              Pair { lo: 0, hi: 0 }, 0));
    print(mix(0, Pair { lo: 2, hi: 3 }, 4,
              Tri { a: 5, b: 6, c: 7 }, Option.Some(0 - 2), 8,
              Pair { lo: 9, hi: 10 }, 11));
    return 0;
}
"""

M4_DEPTH_AGGREGATE = HEADER + STRUCTS + """\
// Recursion to the frame limit carrying an aggregate argument; the
// depth trap bytes are unchanged by M4 (ADR-010 3b; ADR-011 keeps the
// depth discipline identical in the interpreter and the ELF).
fn down(n: i32, p: Pair) -> i32 {
    let q: Pair = Pair { lo: p.lo + 1, hi: p.hi };
    if (n == 0) { return q.lo; }
    return down(n - 1, q);
}

fn deep(n: i32) -> i32 {
    return deep(n + 1);
}

fn main() -> i32 {
    print(down(1022, Pair { lo: 0, hi: 0 }));
    print(1);
    print(deep(0));
    print(2);
    return 0;
}
"""

