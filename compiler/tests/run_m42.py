#!/usr/bin/env python3
"""tests/run_m42.py — M4.2 conformance runner (verification round 2).

Covers compiler/tests/cases_m42/:

  m42_w*_loc*_*.k   aggregate-ABI regression matrix generated by
                    scripts/gen_m42_matrix.py (bug 1: sret pointer vs
                    stack-parameter word collision, SIGSEGV)
  m42_nested*.k     nested match positives on user enums and Option
                    (bug 2: shared arm pool, contiguous-walk corruption)
  err_m42_*.k       negative cases: the 5 nested-match error shapes
                    (S1 pattern type, S2 duplicate, S3 non-exhaustive,
                    S4 arity, S5 unknown variant) plus wildcard/Option
                    extras, each NESTED so the fix is exercised

Positive cases are three-way: ELF == interpreter == reference.py,
byte-exact on stdout, stderr, and exit code.

The capacity-boundary suite lives in run_m42_cap.py (bug 3).
"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
CASES = os.path.join(HERE, "cases_m42")
sys.path.insert(0, HERE)
import reference  # noqa: E402  (the independent oracle)


def run(cmd, **kw):
    # a hang must never escape as a raw traceback (M4.1 follow-up rule)
    try:
        return subprocess.run(cmd, capture_output=True, timeout=60, **kw)
    except subprocess.TimeoutExpired:
        print("TIMEOUT (60s): %s did not finish; reported as a failure "
              "and the suite continues" % " ".join(map(str, cmd)))
        return None


def main():
    if not os.path.exists(os.path.join(ROOT, "kavir")):
        sys.exit("run_m42: ./kavir missing — run 'make' first")

    names = sorted(n for n in os.listdir(CASES) if n.endswith(".k"))
    if not names:
        sys.exit("run_m42: no cases in %s" % CASES)

    passed = failed = 0
    for name in names:
        path = os.path.join(CASES, name)
        case = name[:-2]

        if name.startswith("err_"):
            # negative: pattern on the first line
            with open(path, "r", encoding="utf-8") as f:
                first = f.readline().strip()
            m = re.match(r"^//\s*expect-error:\s*(.+)$", first)
            if not m:
                print("FAIL %s (missing '// expect-error:' line)" % case)
                failed += 1
                continue
            pattern = m.group(1).strip()
            with tempfile.NamedTemporaryFile(delete=False) as tf:
                out_path = tf.name
            try:
                os.unlink(out_path)
            except OSError:
                pass
            r = run([os.path.join(ROOT, "kavir"), "build", path,
                     "-o", out_path])
            if r is None:
                print("FAIL %s (build timed out)" % case)
                failed += 1
                continue
            log = r.stderr.decode("utf-8", "replace")
            ok = (r.returncode == 1
                  and re.search(r":[0-9]+:[0-9]+:", log) is not None
                  and re.search(pattern, log) is not None
                  and not os.path.exists(out_path))
            if ok:
                print("PASS %s (rejected: %s)"
                      % (case, re.search(pattern, log).group(0)))
                passed += 1
            else:
                print("FAIL %s (rc=%d, output_exists=%s)\n  log: %s"
                      % (case, r.returncode, os.path.exists(out_path),
                         log.strip()[:300]))
                failed += 1
            continue

        # positive: three-way
        try:
            exp_out, exp_err, exp_rc = reference.expected_for(path)
        except reference.ReferenceError as e:
            print("FAIL %s (oracle cannot evaluate: %s)" % (case, e))
            failed += 1
            continue

        r = run([os.path.join(ROOT, "kavir"), "interp", path])
        if r is None:
            print("FAIL %s (interpreter timed out)" % case)
            failed += 1
            continue
        i_out, i_err, i_rc = r.stdout, r.stderr, r.returncode

        b = run([os.path.join(ROOT, "kavir"), "build", path,
                 "-o", "/tmp/kavir_m42_prog"])
        if b is None:
            print("FAIL %s (build timed out)" % case)
            failed += 1
            continue
        if b.returncode != 0:
            print("FAIL %s (build failed: %s)"
                  % (case, b.stderr.decode("utf-8", "replace").strip()[:200]))
            failed += 1
            continue
        e = run(["/tmp/kavir_m42_prog"])
        if e is None:
            print("FAIL %s (ELF run timed out)" % case)
            failed += 1
            continue
        e_out, e_err, e_rc = e.stdout, e.stderr, e.returncode

        if (e_out, e_err, e_rc) == (exp_out, exp_err, exp_rc) and \
           (i_out, i_err, i_rc) == (exp_out, exp_err, exp_rc):
            print("PASS %s (out=%d bytes rc=%d)"
                  % (case, len(exp_out), exp_rc))
            passed += 1
        else:
            print("FAIL %s" % case)
            print("  expected: rc=%d out=%r err=%r"
                  % (exp_rc, exp_out[:80], exp_err[:120]))
            print("  interp:   rc=%d out=%r err=%r"
                  % (i_rc, i_out[:80], i_err[:120]))
            print("  elf:      rc=%d out=%r err=%r"
                  % (e_rc, e_out[:80], e_err[:120]))
            failed += 1

    print("M4.2 conformance: %d/%d checks passed"
          % (passed, passed + failed))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
